/* site.mjs — the pieces of the website that aren't the page itself: the
   data blob's escaping, the service worker and the web app manifest.
   build.mjs writes them; the tests check them. */

/** JSON that is safe inside <script>…</script>. Only "</" (which could close
    the tag) and "<!--" (which changes how the tag is parsed) need escaping,
    and "<\/" is a legal JSON escape. Escaping every "<" as <, as this
    used to, cost about 60 KB on a page that is mostly HTML strings. */
export function scriptJson(value) {
  return JSON.stringify(value).replace(/<\//g, "<\\/").replace(/<!--/g, "\\u003c!--");
}

/** The service worker. The page is network-first so a new build shows up
    whenever there's signal; with none, or with one bar that hangs for
    `wait` ms, the cached copy answers and the network copy still lands in
    the cache for next time. Everything else is cache-first. `version`
    names the cache, so each build replaces the last one cleanly. */
export function serviceWorker(version, files, wait = 4000) {
  return `/* Generated by tools/build.mjs. Don't edit; edit tools/lib/site.mjs. */
const VERSION = ${JSON.stringify("tn-" + version)};
const PAGE = "./index.html";
const PRECACHE = ${JSON.stringify(files.map((f) => "./" + f))};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(VERSION)
    .then((c) => c.addAll(PRECACHE.map((u) => new Request(u, { cache: "reload" }))))
    .then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith("tn-") && k !== VERSION).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;
  const scope = new URL(self.registration.scope).pathname;
  const isPage = req.mode === "navigate" || url.pathname === scope || url.pathname === scope + "index.html";
  if (!isPage) {
    e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
    return;
  }
  const net = fetch(new Request(url.origin + url.pathname, { cache: "no-cache", credentials: "same-origin" }))
    .then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(VERSION).then((c) => c.put(PAGE, copy)); }
      return res;
    });
  e.waitUntil(net.catch(() => {}));
  e.respondWith(new Promise((resolve) => {
    let settled = false;
    const give = (res) => { if (res && !settled) { settled = true; resolve(res); } };
    const cached = () => caches.match(PAGE);
    const slow = setTimeout(() => cached().then(give), ${wait});
    net.then((res) => { clearTimeout(slow); give(res); },
      () => { clearTimeout(slow); cached().then((hit) => give(hit || Response.error())); });
  }));
});
`;
}

